#!/usr/bin/env python3
"""Render sim2real/onestep_gap_report.md from model_eval/onestep_gap_float*.json."""
import json, os
R = os.path.dirname(os.path.abspath(__file__))
S = {k: json.load(open(os.path.join(R, f"onestep_gap_float{v}.json")))
     for k, v in (("all", ""), ("after", "_after"), ("upto", "_upto")) if os.path.exists(os.path.join(R, f"onestep_gap_float{v}.json"))}


def grp(d, js):
    import numpy as np
    r = [d["joints"][j] for j in js]
    f = lambda k: float(np.sqrt(np.mean([x[k] ** 2 for x in r])))
    return f("q_rmse"), f("q_persist"), f("dq_rmse"), f("dq_persist")


out = []
w = out.append
w("# One-step teacher-forced sim-vs-real gap, per joint\n")
w("Generated by `model_eval/render_onestep_report.py` from `model_eval/onestep_gap_float*.json` "
  "(script: `model_eval/onestep_gap_per_joint.py`).\n")
w("""**Protocol.** For every step t of every clean real run, the sim is reset to the measured `(q, dq)[t]`
(+ IMU base orientation / angular velocity), the real `q_target[t]` is applied through the deploy PD law
(`tau = kp(q_target-q) - kd*dq`, clipped to effort limits), one 0.02 s control step is simulated and
compared with measured `(q, dq)[t+1]`. Floating base with ground contact, real per-motor armature.
Base linear velocity is not logged and is set to 0. Runs: `list_runs()` (9 known-bad runs excluded,
see `robot_log_data_quality.md`). **persist** = error of predicting "nothing changes"
(`x[t+1] = x[t]`); **ratio** = sim RMSE / persist (< 1: sim beats persistence). q in deg, dq in rad/s.
Biases are sim - real.\n""")
w("""### How to read the columns

| column | meaning |
|---|---|
| **bias** | mean of (sim - real) next-step value; a constant offset. Sign: + means sim is above real. |
| **RMSE** | root-mean-square of (sim - real) next-step value, over all steps. q in deg, dq in rad/s. |
| **persist** | RMSE of the do-nothing predictor (`q[t+1] = q[t]`, `dq[t+1] = dq[t]`), i.e. how much the real robot itself changes in one 0.02 s step. |
| **q ratio** | `q RMSE / q persist`. Sim error in q relative to the real one-step change in q. |
| **dq ratio** | `dq RMSE / dq persist`. Same for velocity. |

**Interpreting a ratio**

- **< 1**: the sim predicts the next step better than "nothing changes", so one step of the model is informative for this joint (lower = better).
- **= 1**: the sim is no better than assuming nothing changes.
- **> 1**: the sim is *worse* than assuming nothing changes. It adds error that the real robot did not have (model error, missing contact or base velocity, noise in the measured start state).

Cautions:

1. The ratio is scale-relative. A joint that barely moves per step (wrist, persist ~0.1-0.2) has a small denominator, so a small absolute error gives a large ratio. Read ratio together with the absolute RMSE.
2. The persistence baseline is strong for **q** (at 50 Hz q barely changes) and weak for **dq** (velocity changes a lot step to step), but the sim's dq starts from a noisy measured `dq[t]`, which also enters the PD term `kd*dq`. Both effects push the dq ratio above 1 on almost every joint; compare joints against each other rather than against 1.
3. A ratio says nothing about the *source* of the error. Bias vs scatter: after 0919 about 11 % of the q squared error and 9 % of the dq squared error is constant bias (`bias^2 / RMSE^2`); the rest is scatter.
4. Group rows in section 2 are root-mean-square across the joints of the group.
""")
w("## 1. Data subsets\n")
w("| subset | runs | steps | moving steps |\n|---|:---:|:---:|:---:|")
names = {"all": "all clean runs", "after": "**after 0919** (0922, 0924, 1001; date > 20260919)",
         "upto": "up to 0919 (0905–0919)"}
for k, d in S.items():
    w(f"| {names[k]} | {d['runs']} | {d['steps']} | — |")
w("")
w("## 2. Group RMSE\n")
w("| subset | group | q RMSE | q persist | dq RMSE | dq persist |\n|---|---|:---:|:---:|:---:|:---:|")
groups = {"legs": range(0, 12), "waist": range(12, 15), "arms": range(15, 29), "all joints": range(29)}
for k, d in S.items():
    for g, js in groups.items():
        a, b, c, e = grp(d, list(js))
        w(f"| {k} | {g} | {a:.3f} | {b:.3f} | {c:.3f} | {e:.3f} |")
w("")
w("## 3. Per joint\n")
for k in ("after", "all", "upto"):
    if k not in S:
        continue
    d = S[k]
    w(f"### 3.{ {'after':1,'all':2,'upto':3}[k] } {names[k]}\n")
    w("| joint | q bias | q RMSE | q persist | q ratio | dq bias | dq RMSE | dq persist | dq ratio |\n"
      "|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|")
    for r in d["joints"]:
        w(f"| `{r['joint']}` | {r['q_bias']:+.3f} | {r['q_rmse']:.3f} | {r['q_persist']:.3f} | {r['q_ratio']:.2f} "
          f"| {r['dq_bias']:+.3f} | {r['dq_rmse']:.3f} | {r['dq_persist']:.3f} | {r['dq_ratio']:.2f} |")
    w("")
    w("Mean absolute error, MAE = mean(|sim - real|) over steps (q in deg, dq in rad/s), next to |bias| and RMSE. "
      "`|bias|/MAE` near 1: the error is mostly a constant offset; near 0: mostly zero-mean scatter. "
      "`MAE/RMSE`: ~0.8 for Gaussian errors; much lower means a few large errors dominate the RMSE.\n")
    w("| joint | q MAE | q \\|bias\\| | q RMSE | q \\|bias\\|/MAE | q MAE/RMSE | dq MAE | dq \\|bias\\| | dq RMSE | dq \\|bias\\|/MAE | dq MAE/RMSE |\n"
      "|---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|")
    import math
    for r in d["joints"]:
        if "q_rel_mae" not in r:
            continue
        # MAE = (sum|e| / sum|real|) * mean|real|  (exact); q stored in rad -> deg
        q_mae = math.degrees(r["q_rel_mae"] * r["q_real_absmean"])
        dq_mae = r["dq_rel_mae"] * r["dq_real_absmean"]
        w(f"| `{r['joint']}` | {q_mae:.3f} | {abs(r['q_bias']):.3f} | {r['q_rmse']:.3f} | {abs(r['q_bias'])/max(q_mae,1e-9):.2f} "
          f"| {q_mae/max(r['q_rmse'],1e-9):.2f} | {dq_mae:.3f} | {abs(r['dq_bias']):.3f} | {r['dq_rmse']:.3f} "
          f"| {abs(r['dq_bias'])/max(dq_mae,1e-9):.2f} | {dq_mae/max(r['dq_rmse'],1e-9):.2f} |")
    w("")
open(os.path.join(os.path.dirname(R), "sim2real", "onestep_gap_report.md"), "w").write("\n".join(out))
print("wrote sim2real/onestep_gap_report.md")

# ---- hand-written analysis, appended after the generated tables --------------------
ANALYSIS = """
## 4. Analysis

**A. Restricting to runs after 0919 changes the picture substantially** (16 runs, 24,000 steps; 0922, 0924, 1001):

| | legs q | waist q | arms q | all q | all dq |
|---|:---:|:---:|:---:|:---:|:---:|
| up to 0919 (42 runs) | 1.88 | 0.91 | 0.38 | 1.27 | 1.03 |
| **after 0919 (16 runs)** | **0.78** | **0.37** | **0.33** | **0.56** | **0.79** |
| persistence (after) | 0.61 | 0.28 | 0.44 | 0.51 | 0.24 |

(q RMSE in deg, dq in rad/s.) The q gap on the legs falls 2.4x and on the waist 2.4x; the all-joint
q RMSE (0.56 deg) is within 10 % of "nothing changes" (0.51). Early-session runs dominate the earlier
averages, so the pooled numbers in section 3.2 overstate the current model gap.

**B. The worst early-run outlier was a session-specific offset, not a model error.** `left_ankle_pitch`
q bias: **+3.92 deg up to 0919 -> -0.21 deg after 0919** (RMSE 5.49 -> 1.64); `left_ankle_roll` bias
+1.84 -> -0.48. A systematic sim-model error would not change sign between sessions. Likely cause: the
left-ankle calibration / hardware state in the early sessions (not verified).
It reinforces the earlier finding that ankle offsets are unstable across sessions.

**C. What remains after 0919** (q ratio = sim RMSE / persistence RMSE):

1. **Sim beats persistence on q for the large-motion joints**: hip pitch/roll/yaw (0.57-0.82), knees
   (0.46-0.47), shoulder pitch/roll (0.26-0.37), elbows (0.40-0.47). This is where one step of the
   model is informative.
2. **Ankles are still bad**: pitch ratio 2.8 (L) / 2.0 (R); roll ratio 3.5 / 3.3. Ankle roll bias is
   **mirrored (-0.48 L / +0.48 R)**, and so are the dq biases (-0.52 / +0.54), consistent with the earlier
   mirrored-offset observation (possible log sign or a roll-axis modelling asymmetry; unverified).
   Ankle pitch dq RMSE is 1.6-2.3 rad/s vs 0.36-0.42 persistence.
3. **Wrist roll / pitch / yaw and shoulder yaw**: q ratios 1.1-3.7 and dq ratios 3-9
   (`left_wrist_roll` dq ratio 9.2, bias +0.67 rad/s). These joints move very little per step, so
   persistence is hard to beat, but `left_wrist_roll` has a clear positive bias (+0.44 deg, +0.67 rad/s)
   that `right_wrist_roll` (+0.09, +0.14) does not.
4. **Waist**: roll and pitch ratios 1.4-1.5 (after 0919) vs 3.4-2.1 for all runs, so the large early waist
   gap (`waist_roll` q RMSE 1.2 deg) was also a property of early sessions. `waist_pitch` has a +0.22 deg bias.
5. **dq is worse than persistence on every joint after 0919** (ratio 1.1-9.2; arms 1.1-5.6). Shoulder
   pitch/roll are closest (1.08-1.19). Part of this is measurement noise in the sampled `dq` that is also
   fed into the PD term `kd*dq` and into the initial condition.

**D. What this means for improving the simulator** (ordered by size of the remaining gap):

1. Ankle pitch/roll (contact-coupled): needs the missing base linear velocity or a contact/foot model;
   the model-free parts (the mirrored roll bias, ankle kd) can be checked on hardware.
2. Wrist/forearm joints: the sim error is relative to a tiny real motion; check friction / damping
   values before spending effort here.
3. Everything else is already near the persistence floor at this timestep; further q-fit gains cannot
   be resolved with one-step teacher forcing.

## 5. Caveats

- **n is small after 0919: 16 runs, 3 sessions** (0922: 4, 0924: 2, 1001: 10, of which 8 are the
  new-policy locomotion runs). 1001 dominates; policy and clip mix differ from earlier sessions, so some of the
  "improvement" could be a different motion distribution rather than a different hardware state. This was
  not separated.
- `g1_run_0925` is excluded by the data-quality filter (NUL-truncated CSVs); `0922/083850` is unreadable.
- Base linear velocity is not logged (set to 0), so leg and ankle rows still contain contact error. They are an
  upper bound on pure model error.
- Only ~11-14 % of steps are moving (dq > 0.3 rad/s on any joint).
- "after 0919" means date strictly greater than 2026-09-19 (the 09-19 runs are in "up to 0919").
- Earlier one-step results in this repo (`phaseC1b` etc.) were flagged noisy; this report only uses
  per-step RMSE/bias, not fitted parameters.
"""
open(os.path.join(os.path.dirname(R), "sim2real", "onestep_gap_report.md"), "a").write(ANALYSIS)
